#!/usr/bin/env python3
"""Turns the hex test vectors of the KVM H.264 protocol (test/unit/fixtures/kvm-h264/vectors.json of the MeshCentral fork) into the C table
kvm_stream_vectors.h that kvm_stream_test.c includes. Run in a container (the host has no interpreters for this):

  docker run --rm -v <MeshCentral worktree>/test/unit/fixtures/kvm-h264:/in:ro -v <this directory>:/out python:3.12-slim \
      python -I /out/gen_stream_vectors.py /in/vectors.json /out/kvm_stream_vectors.h

The header names the source file and its SHA-256, so a changed vectors.json is noticed.
"""
import hashlib
import json
import sys

FIELDS = {
    240: ['ver', 'op', 'flags', 'maxLevelIdc', 'maxW', 'maxH', 'reserved'],
    241: ['seq', 'ts', 'queueMs', 'flags'],
    242: ['ver', 'video', 'ack', 'reason', 'profile_idc', 'level_idc', 'codedW', 'codedH', 'caps', 'gen'],
    243: ['jumboN', 'seq', 'ts', 'flags', 'gen', 'codedW', 'codedH', 'nRects'],
}
MAX_RECTS = 4


def main(src, dst):
    raw = open(src, 'rb').read()
    data = json.loads(raw)
    out = []
    out.append('/* Generated by gen_stream_vectors.py from vectors.json (sha256 %s). Do not edit. */' % hashlib.sha256(raw).hexdigest())
    out.append('#ifndef KVM_STREAM_VECTORS_H\n#define KVM_STREAM_VECTORS_H\n')
    out.append('#define KV_MAX_FIELDS 10\n#define KV_MAX_RECTS %d\n' % MAX_RECTS)
    out.append('typedef struct kv_vector { const char *name; int cmd; unsigned screenW, screenH; const char *expect; const unsigned char *bytes; unsigned long len;')
    out.append('    int nFields; long long f[KV_MAX_FIELDS]; int nRects; unsigned rects[KV_MAX_RECTS][4]; const char *annexHex; } kv_vector;\n')
    entries = []
    idx = 0
    for kind in ('valid', 'invalid'):
        for v in data[kind]:
            hexs = ''.join(v['hex'].split())
            b = bytes.fromhex(hexs)
            ctx = v.get('context') or {}
            name = 'kv_bytes_%d' % idx
            out.append('static const unsigned char %s[] = {%s};' % (name, ','.join(str(x) for x in b) if b else '0'))
            fields = []
            rects = []
            annex = ''
            if kind == 'valid':
                f = v['fields']
                fields = [int(f[k]) for k in FIELDS[v['cmd']]]
                if v['cmd'] == 243:
                    rects = f['rects']
                    annex = f['annexB']
                    assert len(rects) <= MAX_RECTS
            ent = '    { "%s", %d, %d, %d, "%s", %s, %d, %d, {%s}, %d, {%s}, "%s" }' % (
                v['name'], v['cmd'], ctx.get('screenW', 0), ctx.get('screenH', 0), '' if kind == 'valid' else v['reject'],
                name if b else name, len(b), len(fields), ','.join('%dLL' % x for x in fields) if fields else '0',
                len(rects), ','.join('{%s}' % ','.join(str(x) for x in r) for r in rects) if rects else '{0,0,0,0}', annex)
            entries.append(ent)
            idx += 1
    out.append('\nstatic const kv_vector kVectors[] = {')
    out.append(',\n'.join(entries))
    out.append('};')
    out.append('#define KV_COUNT (sizeof(kVectors) / sizeof(kVectors[0]))')
    out.append('#define KV_VALID %d' % len(data['valid']))
    out.append('\n#endif')
    open(dst, 'w').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
